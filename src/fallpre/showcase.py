"""Execute the real pipeline and Agent tools, then retain an honest replay trace.

Observations are synthetic. Agent calls are scripted, not generated by an LLM.
Confirmed alarms take the deterministic fast path before any Agent tool calls.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

from .adapters.channels import PHRASES
from .agent import FallPreventionAgent
from .config import RuleConfig
from .demo import synthetic_human, synthetic_quality, synthetic_site
from .execution import action_key
from .pipeline import ObservationPipeline
from .service import MVPService

SCENARIOS = [
    ("approach_stop_retreat", "接近背包 → 提醒 → 停下 → 远离", 135),
    ("fall_after_upright", "站立后跌倒证据 → 快环报警", 85),
    ("initial_low_pose_review", "初始低姿态 → 等待 → 核查", 85),
]


def run_showcase(output: str | Path) -> dict:
    directory = Path(output)
    directory.mkdir(parents=True, exist_ok=True)
    if any(directory.iterdir()):
        raise FileExistsError("Use an empty directory for a new showcase recording")
    site, rules = synthetic_site(), RuleConfig()
    recording = {"format": "fallpre-showcase-v1", "synthetic_observations": True,
                 "agent_mode": "scripted_real_tool_calls_no_llm", "dry_run": True,
                 "site": site.model_dump(mode="json"), "rules": rules.model_dump(mode="json"),
                 "scenarios": []}
    for scenario_id, title, count in SCENARIOS:
        target = directory / scenario_id
        target.mkdir()
        service = MVPService(rules, db_path=str(target / "events.sqlite3"), dry_run=True)
        agent = FallPreventionAgent(service)
        pipeline = ObservationPipeline(site, rules, track_id=1, source_type="synthetic_showcase")
        scenario = {"id": scenario_id, "title": title, "frames": [], "calls": [], "milestones": [], "actions": []}
        seen_keys, previous_outcomes = set(), {}
        previous_semantics = None
        sequence = 0

        def invoke(name, arguments, source_s, frame_id):
            nonlocal sequence
            begin = time.perf_counter()
            result = agent.invoke(name, arguments)
            elapsed_ms = (time.perf_counter() - begin) * 1000
            sequence += 1
            scenario["calls"].append({"sequence": sequence, "frame_id": frame_id, "t_s": source_s,
                                      "actor": "agent_script", "name": name, "arguments": arguments,
                                      "result": result, "elapsed_ms": round(elapsed_ms, 3)})
            if result.get("error"):
                raise RuntimeError(f"Demo tool call failed: {name}: {result['error']}")
            return result

        try:
            with (target / "snapshots.jsonl").open("w") as stream:
                for i in range(count):
                    t_s = i / 10
                    if scenario_id == "approach_stop_retreat":
                        x = 150 + min(i, 55) * 4 if i < 80 else max(150, 370 - (i-80) * 5)
                        human = synthetic_human(t_s, i, x)
                    else:
                        human = synthetic_human(t_s, i, low=scenario_id == "initial_low_pose_review" or i >= 15)
                    snapshot = pipeline.update([human], [{"class_name": "backpack", "score": 0.99,
                                                          "bbox_px": site.obstacle_anchor_bbox_px}],
                                               synthetic_quality(t_s), t_s, i, site.image_size)
                    decisions = service.ingest_snapshot(snapshot, auto_execute=False)
                    pipeline.feedback(decisions)
                    stream.write(snapshot.model_dump_json() + "\n")
                    call_start = len(scenario["calls"])
                    # Direct deterministic alarm first. This does not wait for the
                    # scripted Agent, and uses the same persistent execution service.
                    for decision in decisions:
                        if not decision.confirmed_alarm:
                            continue
                        for action in decision.allowed_actions:
                            key = action_key(decision, action)
                            if key in seen_keys:
                                continue
                            result = service.execution.execute(decision.decision_id, action, key)
                            sequence += 1
                            scenario["calls"].append({"sequence": sequence, "frame_id": i, "t_s": t_s,
                                "actor": "deterministic_fast_loop", "name": "execution.execute",
                                "arguments": {"decision_id": decision.decision_id, "action_type": action,
                                              "idempotency_key": key}, "result": result.model_dump(mode="json"),
                                "elapsed_ms": None})
                            seen_keys.add(key)
                            scenario["actions"].append({**result.model_dump(mode="json"), "t_s": t_s,
                                                       "frame_id": i, "route": "fast_loop",
                                                       "message": PHRASES[action]})
                    changed = [d for d in decisions if previous_outcomes.get(d.branch) != d.outcome]
                    if changed:
                        invoke("get_realtime_state", {"person_id": site.person_id, "max_age_ms": 500}, t_s, i)
                        if i == 0:
                            invoke("get_personal_context", {"person_id": site.person_id}, t_s, i)
                        for decision in changed:
                            if decision.outcome == "NO_ACTION":
                                continue
                            event = service.store.get_event(decision.event_id)
                            if decision.branch == "fall":
                                invoke("get_event_evidence", {"event_id": event.event_id,
                                       "event_revision": event.revision}, t_s, i)
                            evaluated = invoke("evaluate_" + decision.branch, {
                                "snapshot_id": snapshot.snapshot_id, "event_id": event.event_id,
                                "event_revision": event.revision}, t_s, i)
                            for action in evaluated["allowed_actions"]:
                                key = evaluated["action_keys"][action]
                                if key not in seen_keys:
                                    result = invoke("execute_intervention", {"decision_id": evaluated["decision_id"],
                                        "action_type": action, "idempotency_key": key}, t_s, i)
                                    seen_keys.add(key)
                                    scenario["actions"].append({**result, "t_s": t_s, "frame_id": i,
                                                               "route": "agent_tool", "message": PHRASES[action]})
                                else:
                                    result = service.store.action_by_key(key).model_dump(mode="json")
                                invoke("get_execution_status", {"action_id": result["action_id"]}, t_s, i)
                    outcomes = {d.branch: d.outcome for d in decisions}
                    branch = "prefall" if scenario_id == "approach_stop_retreat" else "fall"
                    decision = next(d for d in decisions if d.branch == branch)
                    event = service.store.get_event(decision.event_id)
                    frame = {"t_s": t_s, "frame_id": i, "snapshot_id": snapshot.snapshot_id,
                        "track_id": human.track_id, "bbox_px": human.bbox_px,
                        "joints": [human.keypoints[j][:2] for j in (5,6,11,12,13,14,15,16)],
                        "behavior": snapshot.behavior.value, "quality": snapshot.quality.validity.value,
                        "obstacle": snapshot.obstacle.status, "motion": snapshot.motion.model_dump(mode="json"),
                        "spatial": snapshot.spatial.model_dump(mode="json"), "fall": snapshot.fall.model_dump(mode="json"),
                        "outcomes": outcomes, "outcome": decision.outcome, "reasons": decision.reasons,
                        "event_id": event.event_id, "event_revision": event.revision,
                        "wait_deadline_s": event.wait_deadline_s,
                        "calls": list(range(call_start, len(scenario["calls"]))),
                        "action_count": len(scenario["actions"])}
                    scenario["frames"].append(frame)
                    semantics = (frame["behavior"], frame["obstacle"], frame["spatial"]["ttc_status"],
                                 frame["fall"]["phase"], decision.outcome)
                    if semantics != previous_semantics:
                        scenario["milestones"].append(i)
                        previous_semantics = semantics
                    previous_outcomes = outcomes
            scenario["milestones"] = sorted(set(scenario["milestones"] + [count-1]))
            actual_actions = service.store.list_actions()
            assert len(actual_actions) == len(scenario["actions"])
            assert all(a.status == "SIMULATED" for a in actual_actions)
            (target / "calls.jsonl").write_text("".join(json.dumps(c, ensure_ascii=False) + "\n" for c in scenario["calls"]))
            (target / "actions.json").write_text(json.dumps(scenario["actions"], ensure_ascii=False, indent=2) + "\n")
            recording["scenarios"].append(scenario)
        finally:
            service.close()
    trace_path = directory / "trace.json"
    trace_path.write_text(json.dumps(recording, ensure_ascii=False, separators=(",", ":")) + "\n")
    summary = {"trace": str(trace_path.resolve()), "data_kind": "synthetic_observations_real_pipeline_and_tools",
               "agent_mode": recording["agent_mode"], "dry_run": True,
               "scenarios": [{"id": s["id"], "frames": len(s["frames"]), "calls": len(s["calls"]),
                              "actions": [{"action_type": a["action_type"], "route": a["route"],
                                           "t_s": a["t_s"], "status": a["status"]} for a in s["actions"]]}
                             for s in recording["scenarios"]]}
    (directory / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    return summary
